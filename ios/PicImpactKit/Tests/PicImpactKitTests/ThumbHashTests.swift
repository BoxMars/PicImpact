    @Test("与 JS 参考实现逐采样点一致", arguments: golden.indices)
    func matchesReference(index: Int) throws {
        let (hash, w, h, total, samples) = Self.golden[index]
        let image = try #require(ThumbHash.decode(base64: hash), "解不开 \(hash)")
        #expect(image.width == w, "宽度不符")
        #expect(image.height == h, "高度不符")
        #expect(image.rgba.count == total * 4, "像素数不符")

        for (pixelIndex, expected) in samples {
            let o = pixelIndex * 4
            let actual = (image.rgba[o], image.rgba[o + 1], image.rgba[o + 2], image.rgba[o + 3])
            #expect(
                actual == expected,
                "第 \(pixelIndex) 个像素不符：期望 \(expected)，实际 \(actual)"
            )
        }
    }

    @Test("脏数据不崩，返回 nil")
    func rejectsGarbage() {
        #expect(ThumbHash.decode(base64: "") == nil)
        #expect(ThumbHash.decode(base64: "!!!not base64!!!") == nil)
        #expect(ThumbHash.decode([]) == nil)
    }
